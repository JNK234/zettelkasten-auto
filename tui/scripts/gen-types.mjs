// Generate src/rpc/schema.ts from the Python-exported JSON Schema
// (../vaultengine/rpc/schema.json), so request/result shapes are defined once.
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {compile} from 'json-schema-to-typescript';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const schemaPath = here('../../vaultengine/rpc/schema.json');
const outPath = here('../src/rpc/schema.ts');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

// Pydantic titles every field ("Path", "Line", ...); json-schema-to-typescript
// would turn each into a named alias (Path2, Line7, ...). Keep model titles only.
const stripFieldTitles = (node, isModel) => {
	if (Array.isArray(node)) return node.map((item) => stripFieldTitles(item, false));
	if (node === null || typeof node !== 'object') return node;
	const out = {};
	for (const [key, value] of Object.entries(node)) {
		if (key === 'title' && !isModel) continue;
		out[key] = key === 'properties'
			? Object.fromEntries(Object.entries(value).map(([name, prop]) => [name, stripFieldTitles(prop, false)]))
			: stripFieldTitles(value, false);
	}
	return out;
};
schema.$defs = Object.fromEntries(Object.entries(schema.$defs).map(([name, def]) => [name, stripFieldTitles(def, true)]));
// Wrap every $defs entry as a property so each becomes a named, exported type.
const wrapper = {
	title: 'VaultRpcSchema',
	type: 'object',
	additionalProperties: false,
	properties: Object.fromEntries(Object.keys(schema.$defs).map((name) => [name, {$ref: `#/$defs/${name}`}])),
	$defs: schema.$defs,
};
const banner = '/* eslint-disable */\n// GENERATED by scripts/gen-types.mjs from vaultengine/rpc/schema.json. Do not edit.\n// Regenerate with: npm run gen:types\n';
const ts = await compile(wrapper, 'VaultRpcSchema', {
	bannerComment: banner,
	additionalProperties: false,
	format: false,
	style: {useTabs: true, singleQuote: true},
});
const methods = Object.keys(schema['x-methods']);
const methodTypes = `\nexport type VaultMethod = ${methods.map((m) => `'${m}'`).join(' | ')};\n`;
if (process.argv.includes('--check')) {
	const current = await readFile(outPath, 'utf8').catch(() => '');
	if (current !== ts + methodTypes) {
		console.error('src/rpc/schema.ts is out of date; run npm run gen:types');
		process.exit(1);
	}
	console.log('src/rpc/schema.ts is up to date');
} else {
	await writeFile(outPath, ts + methodTypes);
	console.log(`wrote ${outPath}`);
}
